import { codeToHtml } from "shiki";

interface CodeBlockProps {
  children: string; // Kode mentah
  language?: string;
  filename?: string;
}

export async function CodeBlock({
  children,
  language = "text",
  filename,
}: CodeBlockProps) {
  // Generate syntax-highlighted HTML with Shiki (server-side only).
  const html = await codeToHtml(children, {
    lang: language,
    // Other themes include 'min-dark', 'github-dark', 'poimandres', and 'vesper'.
    // 'github-dark-dimmed' is a comfortable choice for dark mode.
    theme: "github-dark",
  });

  return (
    <div className="group relative my-6 overflow-hidden rounded-xl border border-border bg-card">
      {/* Header: Filename / Language Label */}
      {(filename || language) && (
        <div className="flex items-center justify-between border-b border-border bg-muted/20 px-4 py-2">
          {filename ? (
            <span className="text-xs font-medium text-muted-foreground">
              {filename}
            </span>
          ) : (
            <span className="text-xs font-bold font-mono text-muted-foreground uppercase tracking-wider">
              {language}
            </span>
          )}
        </div>
      )}

      {/* Render the HTML generated by Shiki. */}
      <div className="overflow-x-auto text-sm">
        {/* - [&>pre]:!bg-transparent -> Remove Shiki's default background to match the container.
           - [&_code]:!font-normal -> Keep code at normal weight.
           - [&_code]:!font-mono -> Use a monospace font.
        */}
        <div
          dangerouslySetInnerHTML={{ __html: html }}
          className="
            p-4 
            [&>pre]:bg-transparent!
            [&>pre]:m-0!
            [&_code]:font-mono!
            [&_code]:text-sm!
            [&_code]:leading-relaxed!
            [&_code]:font-normal!
          "
        />
      </div>
    </div>
  );
}
